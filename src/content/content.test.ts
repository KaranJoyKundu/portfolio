/// <reference types="node" />
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, it, expect } from "vitest";
import { rawProjects } from "@/content/projects";
import { rawAchievements } from "@/content/achievements";
import { projectSchema, achievementSchema } from "@/lib/schema";
import {
  projects,
  featuredProjects,
  placeholderInventory,
  caseStudyOf,
} from "@/lib/content";

/**
 * Content validation at build time — CI runs the test suite, so any
 * schema violation, placeholder leak, or duplicate slug fails the build.
 * Zod is intentionally not shipped in the runtime bundle; this is the
 * enforcement point (see lib/content.ts).
 */

describe("content schema integrity", () => {
  it("parses every project against the schema", () => {
    for (const p of rawProjects) {
      expect(() => projectSchema.parse(p), p.slug).not.toThrow();
    }
    expect(projects.length).toBeGreaterThanOrEqual(5);
  });

  it("parses every achievement against the schema", () => {
    for (const a of rawAchievements) {
      expect(() => achievementSchema.parse(a), a.title).not.toThrow();
    }
  });

  it("has unique slugs", () => {
    const slugs = projects.map((p) => p.slug);
    expect(new Set(slugs).size).toBe(slugs.length);
  });

  it("features exactly three projects in the approved order", () => {
    expect(featuredProjects).toHaveLength(3);
    expect(featuredProjects.map((p) => p.slug)).toEqual([
      "bee-biped-robot",
      "opamp-ecg-heart-rate-monitor",
      "kairos",
    ]);
  });

  it("hides placeholder bodies from production", () => {
    for (const p of projects) {
      if (p.detail?.status === "placeholder") {
        expect(caseStudyOf(p, false)).toBeNull();
        expect(caseStudyOf(p, true)).toEqual(p.detail);
      }
    }
  });

  it("placeholder image blocks carry no figures (nothing fabricated ships)", () => {
    for (const p of projects) {
      if (p.images.status === "placeholder") {
        expect(p.images.figures).toHaveLength(0);
      }
    }
  });

  it("verified achievements always name a source; placeholders never ship", () => {
    const verified = rawAchievements.filter((a) => a.contentStatus === "verified");
    for (const a of verified) {
      expect("source" in a && a.source.length > 0).toBe(true);
    }
  });
});

describe("placeholder inventory report", () => {
  it("writes the CI report and keeps the inventory complete", () => {
    const inventory = placeholderInventory();
    // Bee now ships a case study + photos; the other four still pending.
    expect(inventory.filter((i) => i.kind === "project-detail")).toHaveLength(4);
    expect(inventory.filter((i) => i.kind === "project-images")).toHaveLength(4);

    const report = {
      note: "Auto-generated by content tests. Fields listed here are hidden from production with designed fallbacks (images) or show an in-progress panel (details). Delete a line by supplying real content.",
      generatedAt: new Date().toISOString(),
      placeholders: inventory,
    };
    writeFileSync(
      resolve(process.cwd(), "content-placeholder-report.json"),
      JSON.stringify(report, null, 2) + "\n"
    );
    expect(inventory.length).toBeGreaterThan(0);
  });
});
